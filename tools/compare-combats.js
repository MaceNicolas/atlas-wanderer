// Equivalence of the game before / after a change of data or code: plays many deterministic combats between random boards of the real servants and equipment
// (seeded: the same boards and the same dice every time) and prints a hash of what matters (winner, survivors' statistics, number of frames). The log wording is NOT part of it.
// Usage: node tools/compare-combats.js [directory of a checkout=.] [combats=1500]
//   Before / after:  git worktree add /tmp/aw-head HEAD && node tools/compare-combats.js /tmp/aw-head && node tools/compare-combats.js . && git worktree remove --force /tmp/aw-head
//   Two equal hashes = the same combats. Texts of cards are checked elsewhere (documentation/cartes.md is regenerated by tools/verify-all.sh: git diff shows any change).
'use strict';
const vm = require('vm'), fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.resolve(process.argv[2] || '.'), combats = +process.argv[3] || 1500;
process.chdir(root);
const read = (...p) => fs.readFileSync(path.join(root, ...p), 'utf8');
const g = vm.runInNewContext(['data.js', 'i18n.js', 'powers.js', 'flow.js', 'engine.js'].map(f => read('prototype', f)).join('\n') + require(path.join(root, 'tools', 'engine-data')).installScript()
  + '\n;({ runCombat, mkServant, applyEquip, SERVANTS, EQUIPS, DUNGEONS, setSeed })', { Math, console });
let a = 1; const rnd = () => { a = (a * 1664525 + 1013904223) >>> 0; return a / 4294967296; }, pick = l => l[Math.floor(rnd() * l.length)];
const dungeon = Object.values(g.DUNGEONS)[0], hash = crypto.createHash('sha256');
let n = 0;
for (let i = 1; i <= combats; i++) {
  a = i * 7919; g.setSeed(i);
  const board = () => Array.from({ length: 3 + Math.floor(rnd() * 4) }, () => { const s = g.mkServant(pick(g.SERVANTS.filter(c => !c.token))); if (rnd() < 0.5 && g.EQUIPS.length) { try { g.applyEquip(s, pick(g.EQUIPS)); } catch (e) { /* an equipment that does not fit */ } } return s; });
  const mine = board(), theirs = board();
  const ctx = { heroes: [], level: 1 + i % 5, room: 1 + i % 12, dungeon: { ...dungeon, boss: { ...dungeon.boss, power: null } }, summonBonus: {}, owedEquipment: 0 };
  let res; try { res = g.runCombat(mine, theirs, ctx); } catch (e) { hash.update('ERR ' + e.message); continue; }
  const survivors = list => list.map(s => [s.name, s.atk, s.hp, s.maxhp, (s.kw || []).slice().sort().join('+'), s.shield ? 1 : 0].join(':')).join('|');
  hash.update([res.winner, survivors(mine), survivors(theirs), res.frames.length].join('#')); n++;
}
console.log(`${n} combats ${hash.digest('hex').slice(0, 16)}`);
